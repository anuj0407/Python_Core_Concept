import math
# math module provides mathematical functions
print(math.sqrt(16)) # calculates the square root of 16
print(math.pow(2, 3)) # calculates 2 raised to the power of 3
print(math.pi) # prints the value of pi
print(math.factorial(5)) # calculates the factorial of 5
print(math.gcd(48, 18)) # calculates the greatest common divisor of 48 and 18

#math module also provides functions for trigonometric calculations as well as other mathematical operations.